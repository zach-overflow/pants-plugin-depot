def make_maturin(**overrides: Any) -> Maturin:
    """Builds a `Maturin` subsystem with default option values, without the engine. Keyword args override options."""
    options: dict[str, Any] = {
        "bindings": "pyo3",
        "compatibility": "pypi",
        "interpreter": ["python3.12", "python3.13", "python3.14"],
        "jobs": None,
        "profile_guided_optimization": False,
        "release": True,
        "skip": False,
        "skip_existing": False,
        "extra_env_vars": [],
    }
    options.update(overrides)
    return create_subsystem(Maturin, **options)


@pytest.fixture(scope="function")
def maturin_rule_runner(rule_runner_factory: RuleRunnerFactory) -> RuleRunner:  # ruff: ignore[F811]
    """
    `RuleRunner` with every rule the maturin plugin's `package` path needs.

    Requesting a `BuiltPackage` builds the real `maturin` pex (network) and runs `cargo` from `PATH`.
    """
    rule_runner = rule_runner_factory(
        rules=[
            *package.rules(),
            *maturin_common.rules(),
            *subsystem.rules(),
            *pex.rules(),
            *source_files.rules(),
            *env_vars.rules(),
            QueryRule(BuiltPackage, [MaturinPackageFieldSet]),
            QueryRule(MaturinSources, [MaturinFieldSet]),
            QueryRule(DigestContents, [Digest]),
            QueryRule(Maturin, []),
        ],
        target_types=[MaturinWheelTarget, FileTarget],
    )
    # Mirror `[python].pip_version` in `pants.toml`: Pants' default pip predates CPython 3.14.
    # `bin` bindings need neither pyo3 nor a target interpreter, so the fake crate builds in seconds.
    rule_runner.set_options(
        ["--python-pip-version=latest", "--maturin-interpreter=[]", "--maturin-bindings=bin"],
        env_inherit={"PATH", "HOME", "PYENV_ROOT"},
    )
    return rule_runner


